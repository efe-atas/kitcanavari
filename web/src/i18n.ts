export function t(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  const template = dictionaries[lang][key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`))
}
